import { readFileSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const read = (file) => readFileSync(resolve(root, file), 'utf8')
const failures = []
const expect = (condition, message) => {
  if (!condition) failures.push(message)
}

const game = read('src/bruno-runtime/Game/Game.js')
const app = read('src/App.tsx')
const tableSea = read('src/TableSea.tsx')
const lobby = read('src/Lobby.tsx')
const replay = read('src/live/DiscussionPanel.tsx')
const backend = read('src/live/backend.ts')
const api = read('src/live/api.ts')
const contract = read('src/live/contract.ts')
const handoff = read('src/live/handoff.ts')
const intent = read('src/live/IntentPanel.tsx')
const closingCard = read('src/live/ClosingCard.tsx')
const tableWorld = read('src/TableWorld.tsx')
const sceneBridge = read('src/bruno-runtime/SceneBridge.js')
const tableMeeting = read('src/bruno-runtime/Game/World/TableMeeting.js')
const terrain = read('src/bruno-runtime/Game/Terrain.js')
const mock = read('src/live/mock.ts')
const vite = read('vite.config.ts')

expect(!game.includes('Respawns'), 'Game.js still references the removed Respawns system')
expect(!game.includes('respawnsReferences.glb'), 'Game.js still loads the removed respawn asset')
expect(!app.includes('actorAnchors'), 'App.tsx still owns fixed percentage actor anchors')
expect(!app.includes('humanActors'), 'App.tsx still falls back to fixture participants')
expect(!lobby.includes('humanActors'), 'Lobby.tsx still falls back to fixture participants')
expect(replay.includes('createPortal'), 'DiscussionPanel is not rendered through a Portal')
expect(replay.includes('aria-modal="true"'), 'DiscussionPanel is missing modal semantics')
expect(replay.includes('sourceSignals'), 'DiscussionPanel does not project replay source signals')
expect(replay.includes('!loading && !error && replay'), 'DiscussionPanel renders replay body before the authoritative replay response is ready')
expect(backend.includes("DEFAULT_TABLE_ID = 'learning-to-rest'"), 'frontend default table id is not aligned with the seeded backend table')
expect(backend.includes('viewerIdentity.observerId'), 'observer WebSocket does not use a separate observer identity')
expect(backend.includes('if (!runtime.viewerJoined) return false'), 'backend mutation helpers do not enforce participant membership')
expect(backend.includes('reconcilePendingMessages') && backend.includes('reconcileMessageFromReplay'), 'client message delivery is not reconciled against authoritative replay')
expect(app.includes('joinPending') && app.includes('closePending') && app.includes('nudgePending'), 'room actions are missing duplicate-submit guards')
const hostActions = ['SILENCE', 'PASS', 'PROBE', 'REFRAME', 'GROUND', 'CLOSE']
expect(hostActions.every((action) => app.includes(`${action}:`)), 'App is missing a host action label')
expect(hostActions.every((action) => tableMeeting.includes(`${action}:`)), 'TableMeeting is missing a host action visual mapping')
expect(tableWorld.includes('hostAction') && sceneBridge.includes('setHostAction'), 'host actions are not bridged into the single Bruno scene')
expect(app.includes('retryLobby') && app.includes('refreshDiscovery'), 'entry surfaces are missing recoverable reload actions')
expect(handoff.includes('HOME_TO_MATCH_CONTEXT_EVENT') && handoff.includes('OPEN_TABLE_CONTEXT_EVENT'), 'homepage handoff events are not defined at the shared boundary')
expect((handoff.match(/return dispatched \|\| persisted/g) ?? []).length === 3, 'handoff success is lost when only one transport path is available')
expect(api.includes("'/matches/preview'") && api.includes("'/matches/confirm'"), 'shared REST adapter is missing explicit MatchPlan preview/confirm functions')
expect(api.includes('origin_signal_ids') && api.includes('origin_signals'), 'createTable adapter cannot carry public source provenance')
expect(contract.includes('CreateTableRequestLike') && contract.includes('public_signal_ids'), 'frontend contracts are missing public source provenance fields')
expect(contract.includes('InterventionStateLike') && contract.includes('AgentPresenceLike') && contract.includes('ReplaySourceSignalLike extends PublicContentSignalLike'), 'frontend state/replay contracts are missing backend-owned fields')
expect(app.includes('readHomeContext()') && app.includes('readOpenTableContext()'), 'matching page does not hydrate homepage handoff contexts')
expect(intent.includes('sourcePlan?.preview_token') && intent.includes('confirmSourceMatch'), 'source MatchPlan is missing an explicit confirmation boundary')
expect(closingCard.includes('fetchActionEchoes') && closingCard.includes('item.table_id === tableId'), 'close card is not scoped to the current table action ledger')
expect(tableMeeting.includes('participantSeatMap') && tableMeeting.includes('refreshParticipantSeatMap'), 'scene adapter does not map backend participant IDs to authored seats')
expect(!tableMeeting.includes('addWaterCove') && !tableMeeting.includes('product-table-water-cove'), 'table water cove still uses a standalone product water mesh')
expect(terrain.includes('productWaterCoveNode') && terrain.includes('productWaterAnchor'), 'table water cove is not projected through the Bruno terrain data path')
expect(mock.includes('function schedule(') && mock.includes('schedule(() => hostBeat(index)'), 'mock timers are not centrally tracked for cleanup')
expect(tableWorld.match(/className="bruno-runtime-canvas"/g)?.length === 1, 'TableWorld must mount exactly one Bruno canvas shell')
expect(vite.includes('strictPort: true') && vite.includes('port: 5174'), 'Vite dev server port is not fixed to 5174')
expect(!tableSea.includes('sea-footer'), 'TableSea still renders the removed bottom scene footer')
expect(!app.includes('scene-footer'), 'App still renders the removed bottom scene footer')
expect(app.includes('DrawerToggle') && tableSea.includes('DrawerToggle'), 'scene cards are missing the shared drawer affordance')
expect(existsSync(resolve(root, 'src/experience/ORIGIN.md')), 'source map is missing at the spec path src/experience/ORIGIN.md')
expect(existsSync(resolve(root, 'src/bruno-runtime/REMOVAL-MANIFEST.md')), 'removal manifest is missing')

if (failures.length) {
  console.error(failures.map((failure) => `FAIL: ${failure}`).join('\n'))
  process.exit(1)
}

console.log('frontend verification passed: runtime boundary, backend identity, replay overlay, single canvas, and dev server invariants')
